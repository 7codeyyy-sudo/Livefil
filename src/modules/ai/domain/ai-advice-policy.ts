/**
 * AI 建议的禁区输出拦截（AI-006，FR-083、《接口文档》§11 判定 3）。
 *
 * ## 为什么需要「输出后校验」这一层
 *
 * §11 判定 3 明确要求四类禁区（投资 / 借贷 / 医疗 / 心理诊断）由
 * 「system prompt 约束 + **输出后校验拦截** + 测试点」三重保证。指令（
 * `ai-prompts.ts`）只影响模型倾向，模型仍可能越界——若没有这一层，越界内容会
 * 原样落进草稿并展示给用户。
 *
 * ## 为什么是关键字命中而不是分类模型
 *
 * 与脱敏器同一个理由：确定性。关键字命中可以被穷举启动、可复算、不引入新的
 * 外部依赖与不确定性。代价是可能误伤（例如「理财」出现在用户自己的开销备注里），
 * 因此**本拦截只作用于模型生成的建议文本**，不作用于用户原文回显
 * （`expense_parse` 的 `note` 是用户输入，不是建议）。
 */

/**
 * 四类禁区的命中关键字（FR-083）。
 *
 * 每条对应 SRS 的一项：投资（投资 / 理财 / 股票 / 基金）、借贷（借贷 / 贷款 / 借款）、
 * 医疗（医疗 / 诊断 / 处方 / 用药 / 治疗）、心理（心理诊断 / 抑郁）。
 * 刻意只收「明显属于禁区」的词，不收「焦虑」这类日常词汇——误伤的代价是把一段
 * 正常的作息建议判成失败。
 */
export const PROHIBITED_ADVICE_KEYWORDS = [
  '投资',
  '理财',
  '股票',
  '基金',
  '借贷',
  '贷款',
  '借款',
  '医疗',
  '诊断',
  '处方',
  '用药',
  '治疗',
  '心理诊断',
  '抑郁',
] as const;

/**
 * 在一段文本里找出第一处禁区关键字。
 *
 * @param text 待检查的模型生成文本。
 * @returns 命中的关键字；无命中时为 `null`。
 */
export function findProhibitedAdvice(text: string): string | null {
  for (const keyword of PROHIBITED_ADVICE_KEYWORDS) {
    if (text.includes(keyword)) {
      return keyword;
    }
  }
  return null;
}
